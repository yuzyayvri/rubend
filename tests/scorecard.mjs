import assert from "node:assert/strict";
import {scorecard,compareScorecards} from "../bench/scorecard.mjs";
import {solved,apply} from "../apps/model.mjs";

const cases=[{id:"solved",facelets:solved},{id:"turn",facelets:apply(solved,[0])}];
const done=(elapsedMs,length,lower=0,optimal=0)=>({type:"done",elapsedMs,length,lower,optimal});
const answer=(elapsedMs,moves,lower=0,optimal=0)=>({type:"candidate",elapsedMs,moves,length:moves.length,lower,optimal});
const job=(item,events)=>({...item,mode:"exact",budgetMs:100,status:"ok",events});
const complete=[job(cases[0],[answer(0,[],0,1),done(1,0,0,1)]),job(cases[1],[answer(20,[2],1,1),done(21,1,1,1)])];
const options={deadlines:[10,100],knownOptima:[{id:"solved",length:0,source:"identity"},{id:"turn",length:1,source:"depth-one exhaustive oracle"}]};
const good=scorecard(cases,complete,options);
assert.equal(good.observations[0].answered,1);
assert.equal(good.observations[0].oracle.meanAnsweredExcess,0);
assert.equal(good.observations[0].exact.restrictedMeanMs,5);
assert.equal(good.observations[1].answered,2);
assert.equal(good.observations[1].exact.completed,2);
assert.equal(good.observations[1].exact.restrictedMeanMs,10);
assert.ok(compareScorecards(good,good).every(x=>x.verdict==="tied"));
let rejectedFixtures=0;
const missing=structuredClone(complete);missing[1].events=[done(100,31)];
const partial=scorecard(cases,missing,options),loss=compareScorecards(good,partial).at(-1);
assert.equal(partial.observations[1].meanAnsweredLength,0);
assert.equal(loss.verdict,"regressed-or-tradeoff");
assert.equal(loss.paired.coverageLosses,1);
assert.equal(loss.qualityFloorPassed,false);
const none=structuredClone(missing);none[0].events=[done(100,31)];
const empty=scorecard(cases,none,options);
assert.equal(empty.observations[1].meanAnsweredLength,null);
assert.equal(empty.observations[1].oracle.meanAnsweredExcess,null);
assert.equal(empty.observations[1].exact.restrictedMeanMs,100);
const failed=structuredClone(complete);failed[1]={...failed[1],status:"error",error:"timeout",events:[]};
assert.equal(compareScorecards(good,scorecard(cases,failed,options)).at(-1).verdict,"invalid");
const late=structuredClone(complete);late[1].events=[answer(101,[2],1,1),done(102,1,1,1)];
assert.equal(scorecard(cases,late,options).observations[1].answered,1);
const weak=structuredClone(complete);weak[1].events=[answer(20,[2],0),done(100,1,0)];
const weaker=compareScorecards(good,scorecard(cases,weak,options)).at(-1);
assert.equal(weaker.paired.lowerLosses,1);assert.equal(weaker.qualityFloorPassed,false);
function reject(change){
  const records=structuredClone(complete),input=structuredClone(cases),config=structuredClone(options);
  change(records,input,config);assert.throws(()=>scorecard(input,records,config));rejectedFixtures++;
}
reject(records=>records.pop());
reject(records=>records[1].id="solved");
reject(records=>records[1].id="unknown");
reject(records=>records[1].facelets=solved);
reject(records=>records[1].events[0].moves=[0]);
reject(records=>records[1].events[0].length=2);
reject(records=>records[1].events[0].lower=2);
reject(records=>records[1].events=[answer(20,[2],1),done(21,1,0)]);
reject(records=>records[1].events=[done(20,31,0,1)]);
reject(records=>records[1].events=[answer(20,[2],1),done(19,1,1)]);
reject(records=>records[1].events=[answer(20,[2],1),done(21,2,1)]);
reject(records=>records[1].events.push(done(22,1,1,1)));
reject(records=>records[1].events.pop());
reject(records=>records[1].events.at(-1).reason="time_limit");
reject(records=>records[1].budgetMs=99);
reject((records,input,config)=>config.knownOptima[1].length=2);
reject((records,input,config)=>config.knownOptima[1].source="");
reject((records,input,config)=>config.deadlines=[100,10]);
reject((records,input,config)=>input[1].id="solved");
const changed=structuredClone(good);changed.observations[1].cases[1].facelets=solved;
assert.throws(()=>compareScorecards(good,changed));rejectedFixtures++;
console.log(JSON.stringify({passed:true,positiveFamilies:6,rejectedFixtures,coverageFirst:true,missingAnswersPreserved:true,oracleSubsetExplicit:true,censoredExactTime:true,lowerRegressionsVisible:true}));
